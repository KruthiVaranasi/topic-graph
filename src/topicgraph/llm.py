"""LLM access behind a tiny interface.

Every LLM-backed step (boundary check, labelling, synthetic data generation,
judging) takes an `LLM`: anything with `complete(system, prompt, schema=None)`
returning a string (JSON text when a schema is given). That keeps the pipeline
model-agnostic, so the synthetic data can be generated by one model family and
the pipeline run by another, as the eval plan requires.

`ClaudeLLM` is the bundled adapter. To add another family, write a class with
the same `complete` method around that vendor's SDK.
"""

from __future__ import annotations

import json
import os
from typing import Any, Protocol


class LLM(Protocol):
    name: str

    def complete(self, system: str, prompt: str, schema: dict[str, Any] | None = None) -> str: ...


class ClaudeLLM:
    def __init__(self, model: str | None = None, effort: str = "low", max_tokens: int = 16000):
        import anthropic

        self.client = anthropic.Anthropic()
        self.model = model or os.environ.get("TOPICGRAPH_MODEL", "claude-opus-5-5")
        self.effort = effort
        self.max_tokens = max_tokens
        self.name = self.model

    def complete(self, system: str, prompt: str, schema: dict[str, Any] | None = None) -> str:
        output_config: dict[str, Any] = {"effort": self.effort}
        if schema is not None:
            output_config["format"] = {"type": "json_schema", "schema": schema}
        response = self.client.beta.messages.create(
            model=self.model,
            max_tokens=self.max_tokens,
            system=system,
            messages=[{"role": "user", "content": prompt}],
            output_config=output_config,
            # On a safety decline, let the API retry on a fallback model.
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
        )
        if response.stop_reason == "refusal":
            raise RuntimeError(f"model declined the request: {response.stop_details}")
        return "".join(b.text for b in response.content if b.type == "text")


def complete_json(llm: LLM, system: str, prompt: str, schema: dict[str, Any]) -> Any:
    return json.loads(llm.complete(system, prompt, schema))


def get_llm(spec: str | None) -> LLM | None:
    """`None`/"none" disables LLM steps; "claude" or "claude:<model-id>" selects Claude."""
    if not spec or spec == "none":
        return None
    if spec == "claude":
        return ClaudeLLM()
    if spec.startswith("claude:"):
        return ClaudeLLM(model=spec.split(":", 1)[1])
    raise ValueError(f"unknown LLM {spec!r} (use 'none', 'claude' or 'claude:<model-id>')")
